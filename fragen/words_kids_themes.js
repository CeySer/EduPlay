// Neue Themen automatisch in alle Themen-Auswahlen eintragen
(function () {
    if (typeof document === "undefined") return;
    let geplant = false;
    function auffuellen() {
        geplant = false;
        document.querySelectorAll("select").forEach(sel => {
            if (!sel.querySelector('option[value="fahrzeuge"]')) return;
            Object.keys(KIDS_THEME_LABELS).forEach(k => {
                if (k === "gemischt" || sel.querySelector(`option[value="${k}"]`)) return;
                const o = document.createElement("option");
                o.value = k;
                o.textContent = KIDS_THEME_LABELS[k];
                sel.appendChild(o);
            });
        });
    }
    function planen() {
        if (geplant) return;
        geplant = true;
        (window.requestAnimationFrame || setTimeout)(auffuellen);
    }
    function starten() {
        auffuellen();
        new MutationObserver(planen).observe(document.body, { childList: true, subtree: true });
    }
    if (document.body) starten();
    else document.addEventListener("DOMContentLoaded", starten);
})();
