// Deduplizieren & normalisieren
Object.keys(GERMAN_WORDS_KIDS_THEMES).forEach(key => {
    const arr = GERMAN_WORDS_KIDS_THEMES[key];
    if (!arr) return;
    const seen = new Set();
    GERMAN_WORDS_KIDS_THEMES[key] = arr
        .map(w => String(w).toUpperCase().normalize("NFC").trim())
        .filter(w => w && !w.includes("ß") && !w.includes("ẞ") && !seen.has(w) && (seen.add(w), true));
});

